  // Pre-parse into {w, rows[7] as bitmasks}
  const glyphs = {};
  for (const ch in raw) {
    const rows = raw[ch];
    const w = rows[0].length;
    glyphs[ch] = { w, rows: rows.map(r => parseInt(r.padEnd(w, '0'), 2) || 0) };
  }
  const FALLBACK = glyphs['?'];

  return {
    HEIGHT: 7,
    LINE: 12,
    glyph(ch) { return glyphs[ch] || FALLBACK; },
    width(text) {
      let w = 0;
      for (const ch of text) w += (glyphs[ch] || FALLBACK).w + 1;
      return w ? w - 1 : 0;
    },
    /**
     * Draw text at (x,y) on ctx. opts: {color, shadow, maxChars}
     * Returns pixel width drawn.
     */
    draw(ctx, text, x, y, opts = {}) {
      const color = opts.color || '#404850';
      const shadow = opts.shadow === undefined ? '#c8c8b8' : opts.shadow;
      const n = opts.maxChars === undefined ? text.length : opts.maxChars;
      // maxWidth: if the text would overrun the given pixel width, tighten the
      // inter-letter gap (1 -> 0) so long names still fit their slot instead of
      // spilling out of the box. As a last resort it hard-clips at maxWidth.
      const gap = (opts.maxWidth && Font.width(text) > opts.maxWidth) ? 0 : 1;
      let cx = x;
      let i = 0;
      for (const ch of text) {
        if (i++ >= n) break;
        if (opts.maxWidth && cx - x > opts.maxWidth) break;
        const g = glyphs[ch] || FALLBACK;
        if (ch !== ' ') {
          if (shadow) Font._blit(ctx, g, cx + 1, y + 1, shadow);
          Font._blit(ctx, g, cx, y, color);
        }
        cx += g.w + gap;
      }
      return cx - x;
    },
    _blit(ctx, g, x, y, color) {
      ctx.fillStyle = color;
      for (let r = 0; r < 7; r++) {
        const bits = g.rows[r];
        if (!bits) continue;
        for (let c = 0; c < g.w; c++) {
          if (bits & (1 << (g.w - 1 - c))) ctx.fillRect(x + c, y + r, 1, 1);
        }
      }
    },
  };
